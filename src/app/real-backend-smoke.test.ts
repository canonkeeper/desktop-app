// The development backend writes letters to backend/data/mail-outbox (config.Load).
async function verificationTokenFromOutbox(email: string) {
  const { readdir, readFile } = await import('node:fs/promises');
  const { join } = await import('node:path');
  const outbox = process.env.CANONKEEPER_MAIL_OUTBOX_DIR ?? 'backend/data/mail-outbox';
  const names = (await readdir(outbox)).filter((name) => name.endsWith('.eml')).sort().reverse();
  for (const name of names) {
    const letter = await readFile(join(outbox, name), 'utf8');
    const token = letter.includes(`To: <${email}>`) ? /\/auth\/verify-email#([A-Za-z0-9_-]+)/.exec(letter)?.[1] : undefined;
    if (token) return token;
  }
  throw new Error(`no verification letter for ${email} in ${outbox}`);
}

