function smokeFrontendOrigin() {
  const rawBaseUrl = process.env[frontendBaseUrlEnvKey]?.trim() || defaultFrontendBaseUrl;
  return smokeFrontendOriginFor(rawBaseUrl, process.env[allowNonLocalFrontendEnvKey] === '1');
}

function smokeFrontendOriginFor(rawBaseUrl: string, allowNonLocal = false) {
  const url = new URL(rawBaseUrl);
  if (!allowNonLocal && !isLocalHost(url.hostname)) {
    throw new Error(
      `${frontendBaseUrlEnvKey} must point to localhost/loopback for live smoke tests; non-local targets require ${allowNonLocalFrontendEnvKey}=1 and an isolated disposable environment.`,
    );
  }
  return url.origin;
}

function smokeBackendHealthUrl() {
  return smokeBackendHealthUrlFor(process.env[backendBaseUrlEnvKey]?.trim(), process.env[allowNonLocalBackendEnvKey] === '1');
}

function smokeBackendHealthUrlFor(rawBaseUrl: string | undefined, allowNonLocal = false) {
  if (!rawBaseUrl) {
    throw new Error(`${backendBaseUrlEnvKey} is required for live smoke tests to prove the frontend proxy targets the Go backend.`);
  }
  const url = new URL(rawBaseUrl);
  assertLocalBackendTarget(url, allowNonLocal);
  return new URL('/healthz', url);
}

function smokeBackendApiBaseUrl() {
  return smokeBackendApiBaseUrlFor(process.env[backendBaseUrlEnvKey]?.trim(), process.env[allowNonLocalBackendEnvKey] === '1')
    .toString()
    .replace(/\/$/, '');
}

function smokeBackendApiBaseUrlFor(rawBaseUrl: string | undefined, allowNonLocal = false) {
  if (!rawBaseUrl) {
    throw new Error(`${backendBaseUrlEnvKey} is required for live smoke tests to prove direct Go backend state.`);
  }
  const url = new URL(rawBaseUrl);
  assertLocalBackendTarget(url, allowNonLocal);
  if (url.pathname === '/' || url.pathname === '') {
    url.pathname = '/api/v1';
  }
  return url;
}

function smokeBackendProxyTargetOrigin() {
  return smokeBackendProxyTargetOriginFor(
    process.env[backendProxyTargetEnvKey]?.trim(),
    process.env[backendBaseUrlEnvKey]?.trim(),
    process.env[allowNonLocalBackendEnvKey] === '1',
  );
}

function smokeBackendProxyTargetOriginFor(rawProxyTarget: string | undefined, rawBackendBaseUrl: string | undefined, allowNonLocal = false) {
  if (!rawProxyTarget) {
    throw new Error(`${backendProxyTargetEnvKey} is required for live smoke tests so the frontend proxy cannot fall back to the mock server.`);
  }
  if (!rawBackendBaseUrl) {
    throw new Error(`${backendBaseUrlEnvKey} is required for live smoke tests to compare the frontend proxy target.`);
  }
  const proxyUrl = new URL(rawProxyTarget);
  const backendUrl = new URL(rawBackendBaseUrl);
  assertLocalBackendTarget(proxyUrl, allowNonLocal);
  assertLocalBackendTarget(backendUrl, allowNonLocal);
  const proxyOrigin = proxyUrl.origin;
  const backendOrigin = backendUrl.origin;
  if (proxyOrigin !== backendOrigin) {
    throw new Error(`${backendProxyTargetEnvKey} must target the same Go backend as ${backendBaseUrlEnvKey}; got different origins.`);
  }
  return proxyOrigin;
}

function assertLocalBackendTarget(url: URL, allowNonLocal: boolean) {
  if (allowNonLocal || isLocalHost(url.hostname)) {
    return;
  }
  throw new Error(
    `${backendBaseUrlEnvKey} and ${backendProxyTargetEnvKey} must point to a localhost/loopback backend by default; non-local backend smoke requires ${allowNonLocalBackendEnvKey}=1 and an isolated disposable environment.`,
  );
}

async function expectRealBackendHealth(healthUrl: URL) {
  const response = await fetchWithTimeout(new Request(healthUrl), (request) => globalThis.fetch(request), requestTimeoutMs);
  const body = await response.text();
  if (!response.ok || body.trim() !== 'ok') {
    throw new Error(`Expected Go backend health check at ${healthUrl.origin}/healthz to return ok.`);
  }
}

function isLocalHost(hostname: string) {
  return hostname === 'localhost' || hostname === '127.0.0.1' || hostname === '::1';
}

function uniqueSuffix() {
  const random = globalThis.crypto?.randomUUID?.() ?? `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}`;
  return `${Date.now().toString(36)}-${random.replace(/[^a-z0-9-]/gi, '').slice(0, 12).toLowerCase()}`;
}

function createBrowserLikeFetch(frontendOrigin: string, innerFetch: ApiFetch = (request) => globalThis.fetch(request), timeoutMs = requestTimeoutMs): ApiFetch {
  const cookieJar = new CookieJar();

  return async (request) => {
    const headers = new Headers(request.headers);
    cookieJar.apply(headers);
    if (requiresOrigin(request.method) && !headers.has('origin')) {
      headers.set('origin', frontendOrigin);
    }

    const response = await fetchWithTimeout(new Request(request, { headers }), innerFetch, timeoutMs);
    cookieJar.capture(response.headers);
    return response;
  };
}

function requiresOrigin(method: string) {
  return !['GET', 'HEAD', 'OPTIONS'].includes(method.toUpperCase());
}

async function fetchWithTimeout(request: Request, innerFetch: ApiFetch, timeoutMs: number) {
  const controller = new AbortController();
  const timeout = setTimeout(() => {
    controller.abort(new Error('Timed out waiting for the frontend proxy response.'));
  }, timeoutMs);
  let removeAbortListener = () => {};
  if (request.signal.aborted) {
    controller.abort(request.signal.reason);
  } else {
    const abortFromRequest = () => controller.abort(request.signal.reason);
    request.signal.addEventListener('abort', abortFromRequest, { once: true });
    removeAbortListener = () => request.signal.removeEventListener('abort', abortFromRequest);
  }

  try {
    return await innerFetch(new Request(request, { signal: controller.signal }));
  } finally {
    clearTimeout(timeout);
    removeAbortListener();
  }
}

class CookieJar {
  private readonly cookies = new Map<string, string>();

  apply(headers: Headers) {
    if (this.cookies.size === 0) {
      return;
    }
    headers.set(
      'cookie',
      [...this.cookies.entries()].map(([name, value]) => `${name}=${value}`).join('; '),
    );
  }

  capture(headers: Headers) {
    for (const header of setCookieHeaders(headers)) {
      this.captureHeader(header);
    }
  }

  private captureHeader(header: string) {
    const pair = header.split(';', 1)[0] ?? '';
    const separator = pair.indexOf('=');
    if (separator <= 0) {
      return;
    }
    const name = pair.slice(0, separator).trim();
    const value = pair.slice(separator + 1).trim();
    if (!name) {
      return;
    }
    if (value === '' || /;\s*max-age=0(?:;|$)/i.test(header)) {
      this.cookies.delete(name);
      return;
    }
    this.cookies.set(name, value);
  }
}

function setCookieHeaders(headers: Headers) {
  const withGetSetCookie = headers as Headers & { getSetCookie?: () => string[] };
  const separateHeaders = withGetSetCookie.getSetCookie?.();
  if (separateHeaders && separateHeaders.length > 0) {
    return separateHeaders;
  }

  const combinedHeader = headers.get('set-cookie');
  return combinedHeader ? splitCombinedSetCookieHeader(combinedHeader) : [];
}

function splitCombinedSetCookieHeader(header: string) {
  const values: string[] = [];
  let start = 0;
  for (let index = 0; index < header.length; index += 1) {
    if (header[index] !== ',') {
      continue;
    }
    if (/^\s*[^=;,\s][^=;,]*=/.test(header.slice(index + 1))) {
      values.push(header.slice(start, index).trim());
      start = index + 1;
    }
  }
  values.push(header.slice(start).trim());
  return values.filter(Boolean);
}

function expectStringId(value: unknown, label: string) {
  expect(typeof value, label).toBe('string');
  expect((value as string).length, label).toBeGreaterThan(0);
  return value as string;
}

type ChapterParagraphLike = {
  markdown?: string | null;
  text?: string | null;
};

function chapterContainsText(paragraphs: readonly ChapterParagraphLike[], text: string) {
  return paragraphs.some((paragraph) => `${paragraph.text ?? ''}\n${paragraph.markdown ?? ''}`.includes(text));
}

type JobPollApi = Pick<CanonKeeperApiClient, 'getJob'>;

type JobPollOptions = {
  timeoutMs?: number;
  pollIntervalMs?: number;
  sleep?: (durationMs: number) => Promise<void>;
};

async function waitForJobSucceeded(api: JobPollApi, jobId: string, options: JobPollOptions = {}) {
  const timeoutMs = options.timeoutMs ?? indexingJobTimeoutMs;
  const pollIntervalMs = options.pollIntervalMs ?? jobPollIntervalMs;
  const sleep = options.sleep ?? waitForDelay;
  const deadline = Date.now() + timeoutMs;

  while (Date.now() <= deadline) {
    const job = await api.getJob(jobId);
    if (job.status === 'succeeded') {
      return job;
    }
    if (isFailedTerminalJobStatus(job.status)) {
      throw new Error(`Job ${jobId} reached terminal status ${job.status}.`);
    }
    await sleep(pollIntervalMs);
  }

  throw new Error(`Timed out waiting for job ${jobId} to succeed.`);
}

function isFailedTerminalJobStatus(status: Job['status']) {
  return status === 'failed' || status === 'canceled';
}

function waitForDelay(durationMs: number) {
  return new Promise<void>((resolve) => {
    setTimeout(resolve, durationMs);
  });
}

function jobWithStatus(status: Job['status']): Job {
  return {
    id: 'job-1',
    kind: 'canon_text_index',
    status,
    progress: status === 'succeeded' ? 1 : 0,
    phase: null,
    subject: {
      type: 'canon_text_index',
      projectId: 'project-1',
      sourceView: 'draft',
      catalogRevision: 1,
    },
    result: null,
    error: null,
    canCancel: false,
    expiresAt: null,
    createdAt: '2026-01-01T00:00:00Z',
    updatedAt: '2026-01-01T00:00:00Z',
    links: {
      self: '/api/v1/jobs/job-1',
      cancel: null,
      timeline: null,
    },
  };
}
